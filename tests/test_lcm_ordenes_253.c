{
    int fallos = 0, n = (int)(sizeof C / sizeof C[0]);
    if (!lcm_carga(lcm_ordenes_blob, sizeof lcm_ordenes_blob)) { printf("FALLO: el modelo no carga\n"); return 1; }
    static struct lcm_res r;
    for (int i = 0; i < n; ++i) {
        lcm_traduce(C[i].frase, &r);
        const char *o = r.estado == LCM_FALTA ? r.falta : r.estado == LCM_ORDEN ? r.orden : "";
        if (r.estado != C[i].estado || strcmp(o, C[i].orden) || (r.estado == LCM_ORDEN && r.confirmar != C[i].confirmar)) {
            ++fallos; printf("FALLO: [%s] da %d '%s', se esperaba %d '%s'\n", C[i].frase, r.estado, o, C[i].estado, C[i].orden); }
        if (r.estado == LCM_ORDEN && (strpbrk(r.orden, ";|&<>`$\\") || (strchr(r.orden, '"') && strncmp(r.orden, "write ", 6)))) {
            ++fallos; printf("FALLO: orden con caracteres de shell: %s\n", r.orden); }
        if (r.estado == LCM_ORDEN && !r.confirmar && (!strncmp(r.orden, "rm ", 3) || !strncmp(r.orden, "rmdir ", 6) || !strncmp(r.orden, "kill ", 5) ||
            !strcmp(r.orden, "reboot") || !strcmp(r.orden, "poweroff"))) { ++fallos; printf("FALLO: peligrosa sin confirmar: %s\n", r.orden); }
    }
    printf("  %s prueba del traductor en C: %d casos, %d fallos\n", fallos ? "FALLO" : "ok ", n, fallos);
    return fallos != 0;
}
