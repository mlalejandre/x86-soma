/* modificadores: bit 0..7 = LCtrl LShift LAlt LGUI RCtrl RShift RAlt RGUI */
static const uint16_t modmap[8] = { 0x1D, 0x2A, 0x38, E0 | 0x5B, E0 | 0x1D, 0x36, E0 | 0x38, E0 | 0x5C };

int hid_usage_to_set1(uint8_t usage, uint8_t *out)
{
    if (usage >= sizeof map / sizeof map[0] || map[usage] == 0) return 0;
    uint16_t v = map[usage]; int n = 0;
    if (v & E0) out[n++] = 0xE0;
    out[n++] = (uint8_t)(v & 0xFF);
    return n;
}

static int emit(uint16_t v, int brk, uint8_t *out, int *n, int max)
{
    int need = (v & E0) ? 2 : 1;
    if (*n + need > max) return 0;
    if (v & E0) out[(*n)++] = 0xE0;
    out[(*n)++] = (uint8_t)((v & 0xFF) | (brk ? 0x80 : 0));
    return 1;
}

static int has(const uint8_t r[8], uint8_t u) { for (int i = 2; i < 8; i++) if (r[i] == u) return 1; return 0; }

int hid_kbd_diff(const uint8_t prev[8], const uint8_t cur[8], uint8_t *out, int max)
{
    int n = 0;
    for (int i = 2; i < 8; i++) if (cur[i] == 1) return 0;                    /* ErrorRollOver */
    for (int b = 0; b < 8; b++) if ((cur[0] >> b & 1) && !(prev[0] >> b & 1)) emit(modmap[b], 0, out, &n, max);
    for (int i = 2; i < 8; i++) {
        uint8_t u = prev[i];
        if (u > 3 && !has(cur, u) && u < sizeof map / sizeof map[0] && map[u]) emit(map[u], 1, out, &n, max);
    }
    for (int i = 2; i < 8; i++) {
        uint8_t u = cur[i];
        if (u > 3 && !has(prev, u) && u < sizeof map / sizeof map[0] && map[u]) emit(map[u], 0, out, &n, max);
    }
    for (int b = 0; b < 8; b++) if (!(cur[0] >> b & 1) && (prev[0] >> b & 1)) emit(modmap[b], 1, out, &n, max);
    return n;
}

int hid_mouse_parse(const uint8_t *r, uint32_t len, struct hid_mouse *m)
{
    if (len < 3) return 0;
    m->buttons = r[0]; m->dx = (int8_t)r[1]; m->dy = (int8_t)r[2]; m->wheel = len >= 4 ? (int8_t)r[3] : 0;
    return 1;
}
